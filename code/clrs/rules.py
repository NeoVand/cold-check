"""RULES.md: every fitted rule in words, from results/<task>.json (the kept conditions and the greedy conjunction; the
score is printed only where the conjunction is not exact on training). Pair rules speak of a candidate u and a target v
(u is v's pointer, or the pair (u, v) is in the answer); item rules of an item i; k is the third item."""
import ast, json
from pathlib import Path

HERE = Path(__file__).parent
OPS = {'lt': '<', 'le': '≤', 'eq': '=', 'ge': '≥', 'gt': '>'}


def test(t, x, y):
    if t[0] == 'id':
        return f'{x} = {y}'
    if t[0] == 'cmp':
        return f'{t[1]}[{x}] {OPS[t[3]]} {t[2]}[{y}]'
    if t[0] == 'rel':
        return f'{t[1]}({y}, {x})' if t[2] else f'{t[1]}({x}, {y})'
    if t[0] == 'pcmp':
        return f'{t[1]}({x}, {y}) {OPS[t[3]]} {t[2]}({x}, {y})'
    if t[0] == 'pxr':
        return f'{t[1]}({x}, {y}) {OPS[t[4]]} {t[2]}[{x if t[3] == "x" else y}]'
    if t[0] == 'and':
        return f'{test(t[1], x, y)} and {test(t[2], x, y)}'
    return str(t)


def bit(b, z):
    if b[0] == 'bit':
        return f'{b[1]}[{z}]'
    return f'{b[1]}[{z}] {OPS[b[3]]} {b[2]}'


def leg(l, x, y, k_side):
    s = test(l[0], x, y)
    return s if l[1] is None else f'{s} and {bit(l[1], "k")}'


def feature(f, kind):
    a, b = ('u', 'v') if kind == 'pair' else ('i', 'i')
    if f[0] == 'own':
        return test(f[1], a, b)
    if f[0] == 'bitA':
        return bit(f[1], a)
    if f[0] == 'bitB':
        return bit(f[1], b)
    if f[0] == 'wit':
        return f'some k: [{leg(f[1], a, "k", 1)}] and [{leg(f[2], "k", b, 2)}]'
    if f[0] == 'cnt':
        return f'#{{k: {leg(f[1], "k", "i", 2)}}} {"<" if f[3] == "lt" else "="} #{{k: {leg(f[2], "k", "i", 2)}}}'
    if f[0] == 'tri':
        return f'some k: [{leg(f[1], "k", b, 2)}] and {f[2]}(k, {b}) {OPS[f[4]]} {f[3]}({a}, {b})'
    return str(f)


def lit(s, kind):
    neg = s.startswith('not ')
    f = ast.literal_eval(s[4:] if neg else s)
    return ('not ' if neg else '') + feature(f, kind)


if __name__ == '__main__':
    out = ['# The fitted rules, in words', '', 'Generated by `rules.py` from `results/<task>.json` (the final runs). '
           'A rule is the conjunction of its conditions; where it was not exact on the training answers, the sparse '
           'score that decides among the candidates it lets through is listed too. Pair rules: u is the candidate, v the '
           'target; item rules: i; k is any third item (not u, not v / not i). "not yet" values compare false with each other.', '']
    files = {f.stem: f for f in (HERE / 'results').glob('*.json')}
    files.update({f.stem: f for f in (HERE / 'results_extra_heldout').glob('*.json')})   # the 11 added after the freeze
    for t in sorted(files):
        r = json.load(open(files[t]))
        if not r.get('rules'):
            out += [f"## {r['task']}", '', 'No task-specific rule: the DFS check run twice (Kosaraju) and a closure read-out (dfs2.py).', '']
            continue
        out += [f"## {r['task']}", '']
        for name, rule in r['rules'].items():
            if not isinstance(rule, dict) or 'gate' not in rule:
                continue
            kind = 'pair' if name in ('off', 'emask', 'srcptr') or name.startswith('cat') else 'item'
            info = rule['info']
            head = {'off': 'pointer u of v (u ≠ v)', 'diag': 'v points to itself (none)', 'one': 'the chosen item',
                    'mask': 'item selected', 'emask': 'pair in the answer', 'srcptr': "the source's own cell",
                    'cat0': 'arrow = match', 'cat1': 'arrow = up', 'cat2': 'arrow = left', 'end': 'the end item',
                    'start': 'the start item (reads the end)', 'all': 'every item passes (read-out: yes iff all pass)',
                    'head': 'the last finished item'}.get(name, name)
            lv = f", answer read downward along {info['level'][0]} ({info['level'][1]})" if info.get('level') else ''
            out.append(f"**{head}** ({info['gate'] - info.get('greedy', 0)} own conditions + {info.get('greedy', 0)} "
                       f"by the greedy conjunction; exact on training: {'yes' if rule['exact_gate'] else 'no'}{lv})")
            out += [f'- {lit(g, kind)}' for g in rule['gate']]
            if not rule['exact_gate']:
                out.append('- score (decides among the candidates passing): ' +
                           '; '.join(f'{w:+.2f} × [{lit(s, kind)}]' for s, w in rule['score'][:8]))
            out.append('')
    (HERE / 'RULES.md').write_text('\n'.join(out))
    print('\n'.join(out[:60]))
