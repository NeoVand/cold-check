"""Boards for Fig. 3: Sudoku at four sizes and one 100 x 100 N-Queens board, each cell marked given, set by the cold
stage alone (the fitted check's propagation before any search), or set during the search. Solved by the final engine
(code/bench/final/run_final.py: unit pairs on, Luby restarts base 10^4, budget 10^7 moves), with the benchmark's own
code imported read-only from code/bench:
  the check     run_sudoku_sizes.the_check (the train-s0 9 x 9 fit, used unchanged at every size)
  4 x 4, 16 x 16  puzzle 0 of each size, regenerated by run_sudoku_sizes.make_puzzle with its own seed ([1000 + b, 0])
  9 x 9         Sudoku-Extreme test puzzles in order, solved with the final run's train-s0 seeds (seed = index): the first
                whose search takes at least the final median number of moves (code/bench/final/summary.json)
  25 x 25       puzzle 0 of the 25 x 25 set (code/bench/sudoku25b.json), seed 7 as in the final ladder; its move count is
                asserted equal to code/bench/final/sudoku_ladder_25.json
  N-Queens 100  case 0 of '7/8 of the queens removed' at N = 100, regenerated as run_multi.py does, multi.solve_r
The cold stage is the engine's own propagate2 (with unit pairs) / multi.propagate on the starting state.
    python data/puzzle_boards.py          (numpy, numba)
"""
import json
import os
import sys
from pathlib import Path

import numpy as np

CODE = Path(os.environ.get('COLDCHECK_DATA', Path(__file__).resolve().parents[4] / 'code'))
B = CODE / 'bench'
sys.path.insert(0, str(B))
import data_io  # noqa: E402
import engine  # noqa: E402
import multi as Q  # noqa: E402
import run_sudoku_sizes as RS  # noqa: E402

OUT = Path(__file__).resolve().parent / 'puzzle_boards.json'
FIN = json.loads((B / 'final' / 'summary.json').read_text())
BUDGET, RESTART = FIN['budget'], FIN['restart_base']
ck = RS.the_check()


def cold_and_solve(E, puz, seed):
    n = E['V']
    if 'pairs' not in E:
        E['pairs'] = engine.pairs_for(E)
    pa, pb, inb, bout, bout_n = E['pairs']
    dom = engine.masks(puz, n).copy()
    assert engine.propagate2(dom, E['unit_items'], E['unit_size'], E['item_units'], E['ge1'], E['le1'], E['V'],
                             np.zeros(len(E['unit_size']), np.int64), np.ones(len(E['unit_size']), np.bool_),
                             np.zeros(2, np.int64), pa, pb, inb, True, bout, bout_n)
    cold = engine.decode(dom)
    d, o = engine.run2(E, engine.masks(puz, n), seed=seed, budget=BUDGET, use_pairs=True, restart_base=RESTART)
    x = engine.decode(d)
    assert o[0] == 1 and RS.valid(x, int(round(n ** 0.5)))
    kind = np.where(puz > 0, 0, np.where(cold > 0, 1, 2))           # 0 given, 1 cold, 2 search
    return x, kind, o


res = {'sudoku': {}, 'engine': dict(budget=BUDGET, restart_base=RESTART, unit_pairs=True)}
for b in (2, 4):
    E = engine.build(ck, b)
    puz, sol = RS.make_puzzle(E, b, np.random.default_rng([1000 + b, 0]), None)
    x, kind, o = cold_and_solve(E, puz, 7)
    assert (x == sol).all()
    res['sudoku'][b * b] = dict(puzzle=puz.tolist(), solution=x.tolist(), kind=kind.tolist(), moves=int(o[1]))
ts, tc, tr = data_io.sudoku_split('test')
med = FIN['sudoku_extreme'][0]['moves_median']
E = engine.build(ck, 3)
for i9 in range(1000):
    puz = np.where(tc[i9], ts[i9], 0).astype(np.int64)
    x, kind, o = cold_and_solve(E, puz, i9)
    if o[1] >= med:
        break
assert (x == ts[i9]).all()
res['sudoku'][9] = dict(puzzle=puz.tolist(), solution=x.tolist(), kind=kind.tolist(), moves=int(o[1]), test_index=i9,
                        rating=int(tr[i9]), median_moves=med)
r25 = json.loads((B / 'sudoku25b.json').read_text())['rows'][0]
rec25 = json.loads((B / 'final' / 'sudoku_ladder_25.json').read_text())['rows'][0]
E = engine.build(ck, 5)
puz = np.array(r25['puzzle'], np.int64)
x, kind, o = cold_and_solve(E, puz, 7)
assert rec25['i'] == 0 and int(o[1]) == rec25['moves'] and rec25['good'], (o[1], rec25['moves'])
res['sudoku'][25] = dict(puzzle=puz.tolist(), solution=x.tolist(), kind=kind.tolist(), moves=int(o[1]))
qk = Q.queens_check()[0]
N = 100
ui, us, iu, ge, le = Q.queens_engine(qk, N)
rng = np.random.default_rng([N, 0, 7])
cols = Q.min_conflicts(N, int(rng.integers(1 << 30)), 10 ** 4)
while not (cols >= 0).all():
    cols = Q.min_conflicts(N, int(rng.integers(1 << 30)), 10 ** 4)
keep = rng.permutation(N)[N - N // 8:]
dom = np.full(N * N, 3, np.int64)
for r in keep:
    dom[r * N:(r + 1) * N] = 1
    dom[r * N + cols[r]] = 2
d0 = dom.copy()
assert Q.propagate(d0, ui, us, iu, ge, le, 2, np.ones(len(us), np.bool_), np.zeros(2, np.int64))
o = np.zeros(6, np.int64)
d = Q.solve_r(dom, ui, us, iu, ge, le, 2, 1, BUDGET, o, RESTART)
board = (d == 2).astype(int)
assert o[0] == 1 and Q.queens_valid(board, N) and all(board[r * N + cols[r]] == 1 for r in keep)
given = sorted(int(r) for r in keep)
res['queens'] = dict(N=N, cols=[int(np.nonzero(board[r * N:(r + 1) * N])[0][0]) for r in range(N)], given_rows=given,
                     cold_rows=[r for r in range(N) if r not in given and (d0[r * N:(r + 1) * N] == 2).any()],
                     moves=int(o[1]), note='7/8 of the queens removed (88), case 0 of run_multi.py')
OUT.write_text(json.dumps(res))
for s, v in res['sudoku'].items():
    kk = np.array(v['kind']); print(s, 'given', (kk == 0).sum(), 'cold', (kk == 1).sum(), 'search', (kk == 2).sum(), 'moves', v['moves'])
print('queens given', len(given), 'cold', len(res['queens']['cold_rows']), 'moves', o[1])
