"""Supplementary Note 2: the fitted rules of all thirty CLRS-30 tasks, typeset from code/clrs/RULES.md, which
code/clrs/rules.py writes from the final result files. No rule is typed by hand.  Run: python3 paper/gen/make_rules.py"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.environ.get('COLDCHECK_DATA', os.path.join(os.path.dirname(os.path.dirname(HERE)), 'code'))
SRC = os.path.join(DATA, 'clrs', 'RULES.md')

NAMES = dict(
    insertion_sort='Insertion sort', bubble_sort='Bubble sort', heapsort='Heapsort', quicksort='Quicksort',
    minimum='Minimum', binary_search='Binary search', quickselect='Quickselect', activity_selector='Activity selection',
    task_scheduling='Task scheduling', bfs='Breadth-first search', mst_kruskal='Kruskal', mst_prim='Prim',
    lcs_length='Longest common subsequence', naive_string_matcher='Naive string matcher', kmp_matcher='KMP matcher',
    bellman_ford='Bellman--Ford', dijkstra='Dijkstra', dag_shortest_paths='Shortest paths in an acyclic graph',
    floyd_warshall='Floyd--Warshall', graham_scan='Graham scan', jarvis_march='Jarvis march',
    segments_intersect='Segments intersect', matrix_chain_order='Matrix chain order', optimal_bst='Optimal BST',
    find_maximum_subarray_kadane='Maximum subarray', articulation_points='Articulation points', bridges='Bridges',
    dfs='Depth-first search', topological_sort='Topological sort', strongly_connected_components='Strong components')
ORDER = list(NAMES)
GROUP = {t: (1 if i < 15 else 2 if i < 24 else 3) for i, t in enumerate(ORDER)}
GNAME = {1: 'Comparisons and counts', 2: 'One arithmetic primitive supplied',
         3: 'Algorithmic structure supplied'}


def ident(m):
    w = m.group(0)
    if w in ('and', 'not', 'some', 'or', 'k', 'u', 'v', 'i', 'iff'):
        return w
    return r'\mathrm{' + w.replace('_', r'\_') + '}'


def cond(s):
    """One condition, as LaTeX math in running text."""
    s = s.strip().replace('{', '\x01').replace('}', '\x02')
    s = re.sub(r'\[(.+?)\] and \[\1\]', r'[\1]', s)      # the template fills both legs; print a repeated leg once
    s = s.replace('≥', r' \geq ').replace('≤', r' \leq ').replace('≠', r' \neq ').replace('×', r'\times')
    s = re.sub(r'([A-Za-z_]+)\[([a-z])\]', lambda m: m.group(1) + '@' + m.group(2), s)   # key[u] -> key_u
    s = s.replace('#', r'\#').replace('[', '(').replace(']', ')')
    s = re.sub(r'(?<![\\a-zA-Z@])[A-Za-z][A-Za-z_]*', ident, s)
    s = re.sub(r'@([a-z])', r'_{\1}', s)
    s = s.replace('\x01', r'\{').replace('\x02', r'\}')
    s = re.sub(r'\b(and|not|some|iff)\b', r'\\text{ \1 }', s)
    s = s.replace('+', '+').replace('-', '-')
    return '$' + s + '$'


text = open(SRC).read()
blocks = re.split(r'^## ', text, flags=re.M)[1:]
by = {}
for b in blocks:
    name, body = b.split('\n', 1)
    by[name.strip()] = body
out = ['% Generated by gen/make_rules.py from code/clrs/RULES.md. Do not edit by hand.']
g_prev = None
for t in ORDER:
    if t not in by:
        continue
    if GROUP[t] != g_prev:
        out.append(f'\\medskip\\noindent\\textit{{{GNAME[GROUP[t]]}}}\\par')
        g_prev = GROUP[t]
    out.append(f'\\paragraph{{{NAMES[t]}.}}')
    body = by[t].strip()
    if not body.startswith('**'):
        out.append(body.replace('RESULTS.md', 'Methods') + '\n')
        continue
    items = []
    for line in body.split('\n'):
        line = line.strip()
        m = re.match(r'\*\*(.+?)\*\* \((.+)\)$', line)
        if m:
            head, note = m.group(1), m.group(2)
            note = re.sub(r'(\d+) own conditions \+ (\d+) by the greedy conjunction',
                          lambda mm: f'{mm.group(1)} kept, {mm.group(2)} added', note)
            note = note.replace('exact on training: yes', 'exact on the training answers')
            note = note.replace('exact on training: no', 'not exact on the training answers; the score decides')
            note = re.sub(r'answer read downward along (\w+) \((\w+)\)', r'answer read downward along \1', note)
            note = note.replace('_', r'\_')
            head = re.sub(r'\b([uvik])\b', r'$\1$', head.replace('(u ≠ v)', '(u NEQ v)')).replace('$u$ NEQ $v$', '$u \\neq v$')
            head = head.replace('_', r'\_')
            items.append(f'\\emph{{{head}}} ({note}):')
        elif line.startswith('- score'):
            sc = line[len('- score (decides among the candidates passing): '):]
            terms = [x.strip() for x in sc.split(';')]
            terms = [re.sub(r'^([+-][\d.]+) × \[(.*)\]$', lambda mm: f'{mm.group(1)}\\,[{cond(mm.group(2))}]', x)
                     for x in terms]
            items.append('score: ' + '; '.join(terms) + '.')
        elif line.startswith('- '):
            items.append('\\quad ' + cond(line[2:]) + ';')
    out.append('\\\\\n'.join(items) + '\n')
open(os.path.join(HERE, 'rules.tex'), 'w').write('\n'.join(out) + '\n')
print('wrote rules.tex:', sum(1 for t in ORDER if t in by), 'tasks')

