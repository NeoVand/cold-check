import ast
import json
OP = dict(lt='<', le=r'\leq', eq='=', ge=r'\geq', gt='>')


def nm(s):
    return r'\mathrm{' + s.replace('_', r'\_') + '}'


def test(t, x, y):
    kind = t[0]
    if kind == 'rel':
        return f"{nm(t[1])}({x},{y})" if t[2] == 0 else f"{nm(t[1])}({y},{x})"
    if kind == 'cmp':
        return f"{nm(t[1])}_{{{x}}} {OP[t[3]]} {nm(t[2])}_{{{y}}}"
    if kind == 'pcmp':
        return f"{nm(t[1])}({x},{y}) {OP[t[3]]} {nm(t[2])}({x},{y})"
    if kind == 'and':
        return test(t[1], x, y) + r' \wedge ' + test(t[2], x, y)
    if kind == 'id':
        return f"{x} = {y}"
    raise ValueError(t)


def leg(l, x, y):
    s = test(l[0], x, y)
    if l[1] is not None:
        s += r' \wedge ' + f"{nm(l[1][1])}_k"
    return s


def feat(f, item):
    a, b = ('i', 'i') if item else ('u', 'v')
    kind = f[0]
    if kind in ('bitA', 'bitB'):
        return f"{nm(f[1][1])}_{{{a if kind == 'bitA' else b}}}"
    if kind == 'own':
        return test(f[1], a, b)
    if kind == 'wit':
        return rf"\exists k: {leg(f[1], a, 'k')} \wedge {leg(f[2], 'k', b)}"
    if kind == 'tri':
        return rf"\exists k: {leg(f[1], 'k', b)} \wedge {nm(f[2])}(k,{b}) {OP[f[4]]} {nm(f[3])}({a},{b})"
    if kind == 'cnt':
        return rf"\#\{{k: {leg(f[1], 'k', 'i')}\}} {OP[f[3]]} \#\{{k: {leg(f[2], 'k', 'i')}\}}"
    raise ValueError(f)


SH = os.path.join(DATA, 'clrs', 'final', 'shared.json')
if os.path.exists(SH):
    sh = json.load(open(SH))
    lines = ['% Generated by gen/make_rules.py from code/clrs/final/shared.json. Do not edit by hand.']
    for key, title in (('C_bfs_prim_paths_no_task_bit', 'One check for breadth-first search, Prim, Bellman--Ford, '
                                                         'Dijkstra and DAG shortest paths, no task named'),
                       ('D_mask_all_no_task_bit', 'One check for activity selection, task scheduling, Graham scan, '
                                                  'Jarvis march and articulation points, no task named')):
        lines.append(f'\\paragraph{{{title}.}}')
        items = []
        for r, v in sh[key]['rules'].items():
            head = {'off': 'pointer $u$ of $v$ ($u \\neq v$)', 'diag': '$v$ points to itself (none)',
                    'mask': 'item selected'}[r]
            how = 'exact on the training answers' if v['exact'] else \
                'not exact on the training answers; a learned score decides among the candidates that pass'
            items.append(f'\\emph{{{head}}} ({how}):')
            for f, pol in v['kept']:
                s = feat(ast.literal_eval(f), r != 'off')
                items.append('\\quad $' + ('' if pol else r'\text{not } ') + s + '$;')
        lines.append('\\\\\n'.join(items) + '\n')
    open(os.path.join(HERE, 'shared_rules.tex'), 'w').write('\n'.join(lines) + '\n')
    print('wrote shared_rules.tex')
